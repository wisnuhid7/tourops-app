import { describe, it, expect } from "vitest";
import { insertTourDayItemSchema, insertTourSchema, insertTourDaySchema } from "@workspace/db";

describe("Tour Generator AI Save validation", () => {
  it("validates tour day item with numeric cost (as generated by AI)", () => {
    const itemSchema = insertTourDayItemSchema.omit({ tourDayId: true });
    const aiItem = {
      itemType: "sight",
      startTime: "09:00",
      title: "Sightseeing in Bali",
      description: "Local highlights",
      cost: 150,
      sightId: "s-1",
      needsConfirmation: false,
    };

    const result = itemSchema.safeParse(aiItem);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.cost).toBe("150");
      expect(result.data.title).toBe("Sightseeing in Bali");
    }
  });

  it("validates tour day item with string cost", () => {
    const itemSchema = insertTourDayItemSchema.omit({ tourDayId: true });
    const item = {
      itemType: "hotel",
      startTime: "18:00",
      title: "Resort in Bali",
      cost: "250.50",
    };

    const result = itemSchema.safeParse(item);
    expect(result.success).toBe(true);
    if (result.success) {
      expect(result.data.cost).toBe("250.50");
    }
  });

  it("validates tour and day schema when prices and day fields are properly structured", () => {
    const payload = {
      title: "5 Days in Bali for family",
      slug: "5-days-in-bali-for-family-12345",
      description: "A generated itinerary for Bali.",
      duration: 5,
      category: "cultural",
      highlights: "Experience the best of Bali.",
      inclusions: "Accommodation, Breakfast, Transport",
      exclusions: "Flights, Personal expenses, Insurance",
      internalNotes: "Standard package",
      basePrice: "2500",
      childPrice: "2000",
      singleSupplement: "750",
      countries: ["Indonesia"],
      tags: ["leisure", "sightseeing", "bali"],
      galleryUrls: [],
      imageUrl: "https://picsum.photos/seed/tour/1200/800",
    };

    const tourResult = insertTourSchema.safeParse(payload);
    expect(tourResult.success).toBe(true);

    const dayData = {
      dayNumber: 1,
      title: "Day 1 in Bali",
      city: "Bali",
      countryCode: "ID",
      description: "Exploring Bali",
      activities: "Sightseeing, Temple tour",
      imageUrl: "https://picsum.photos/seed/day0/800/600",
      tourId: "new-tour",
    };

    const dayResult = insertTourDaySchema.safeParse(dayData);
    expect(dayResult.success).toBe(true);
  });

  it("ensures child price does not exceed adult base price", () => {
    const invalidPayload = {
      title: "Luxury Paris Getaway",
      slug: "luxury-paris-getaway",
      basePrice: "1000",
      childPrice: "1500", // exceeds base
      duration: 3,
    };
    const result = insertTourSchema.safeParse(invalidPayload);
    expect(result.success).toBe(false);

    // Normalizing child price to min(basePrice, childPrice) fixes it:
    const normalized = {
      ...invalidPayload,
      childPrice: String(Math.min(Number(invalidPayload.basePrice), Number(invalidPayload.childPrice))),
    };
    const normalizedResult = insertTourSchema.safeParse(normalized);
    expect(normalizedResult.success).toBe(true);
  });

  it("verifies slug generation and title requirement", () => {
    const emptyTitle = "   ";
    expect(!emptyTitle.trim()).toBe(true);

    const rawTitle = "Explore Ancient Rome & Vatican City!";
    const baseSlug = rawTitle.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)+/g, '');
    const generatedSlug = (baseSlug || 'tour') + '-' + 123456789;
    expect(generatedSlug).toBe("explore-ancient-rome-vatican-city-123456789");
  });
});

